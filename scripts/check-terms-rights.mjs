#!/usr/bin/env node

import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pagePath = resolve(projectRoot, "app/terms-of-service/page.tsx");
const canonical = "https://mysquarefaceicon.com/terms-of-service";
const description = "Terms of Service for My Square Face Icon, a free square face icon generator.";
const updated = "Last updated: September 2, 2026";
const generatedCopy = "We have not verified personal or commercial usage permissions for images produced by the Square and Oval Flash games on this site. These terms do not grant a license to third-party game artwork or generated images. Before using an image, check the applicable license or obtain the permission needed for your intended use.";
const gameHeading = "Third-Party Game Files";
const gameCopy = "The Square and Oval players run third-party Flash (SWF) files through Ruffle. We have not verified the original source, rights holder, or permissions to host, publicly run, or redistribute the exact files used here. Availability on this site must not be treated as proof of authorization or official affiliation. These terms do not grant permission to extract, redistribute, or reuse third-party game files.";
const acceptedKwCopy = "Read these terms of service before using a generated icon, submitting a comment or image, or relying on the tool for a particular browser workflow.";
const headings = [
  "Terms of Service: Use of the Tool",
  "Generated Icons",
  "Comments and Uploads",
  gameHeading,
  "No Warranty",
  "Future Changes",
  "Contact and Corrections"
];

const plain = (value) => value.replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
const contents = (value, tag) => [...value.matchAll(new RegExp(`<${tag}\\b[^>]*>([\\s\\S]*?)<\\/${tag}>`, "gi"))].map((match) => plain(match[1]));
const attributes = (tag) => Object.fromEntries([...tag.matchAll(/([\w:-]+)="([^"]*)"/g)].map((match) => [match[1].toLowerCase(), match[2]]));

function checkMarkup(markup) {
  const mains = [...markup.matchAll(/<main\b[^>]*>([\s\S]*?)<\/main>/gi)];
  assert.equal(mains.length, 1, "exactly one main is required");
  const main = mains[0][1];
  assert.deepEqual(contents(main, "h1"), ["Terms of Service"]);
  assert.deepEqual(contents(main, "h2"), headings);
  const paragraphs = contents(main, "p");
  assert.equal(paragraphs.length, 8, "paragraph structure changed");
  assert.equal(paragraphs[0], updated, "visible content-update date changed");
  assert.equal(paragraphs[2], generatedCopy, "generated-image rights copy differs from confirmation");
  assert.equal(paragraphs[4], gameCopy, "game-file rights copy differs from confirmation");
  assert.ok(paragraphs[1].endsWith(acceptedKwCopy), "accepted KW-02 sentence changed");
  assert.equal((plain(main).match(/terms of service/gi) || []).length, 3, "KW-02 main coverage changed");
  assert.doesNotMatch(plain(main), /Authorized Game File|authorized SWF|You may use icons generated by the first version/i);
  const links = [...main.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi)].map((match) => ({
    href: attributes(match[1]).href,
    text: plain(match[2])
  }));
  assert.deepEqual(links, [
    { href: "/", text: "Back to Square Face Generator" },
    { href: "/contact", text: "contact page" }
  ]);
  return { paragraphs, headings: contents(main, "h2"), links };
}

function checkSource(source) {
  const result = checkMarkup(source);
  // This approval permits only these three text regions; all other source stays frozen.
  const preserved = source.replace(/\r\n/g, "\n")
    .replace(/<h2>Generated Icons<\/h2>\s*<p>[\s\S]*?<\/p>/, "__GENERATED_ICONS__")
    .replace(/<h2>(?:Authorized Game File|Third-Party Game Files)<\/h2>\s*<p>[\s\S]*?<\/p>/, "__GAME_FILES__")
    .replace(/<p>Last updated: [^<]+<\/p>/, "__UPDATED_DATE__");
  assert.equal(createHash("sha256").update(preserved).digest("hex"),
    "fbdc5eb48c406ab9e2c779503d89ec93ae5e8821de3fc3e22f8ec29bd1981c6f",
    "unapproved source region changed: metadata, imports, layout, links or other copy");
  return result;
}

function checkDocument(html, expectedMarkup) {
  assert.deepEqual(checkMarkup(html), expectedMarkup, "raw HTML differs from the checked source");
  const head = html.match(/<head\b[^>]*>([\s\S]*?)<\/head>/i)?.[1];
  assert.ok(head, "raw HTML head is missing");
  assert.deepEqual(contents(head, "title"), ["Terms of Service | My Square Face Icon"]);
  const meta = [...head.matchAll(/<meta\b[^>]*>/gi)].map((match) => attributes(match[0]));
  assert.deepEqual(meta.filter((tag) => tag.name === "description").map((tag) => tag.content), [description]);
  const canonicals = [...head.matchAll(/<link\b[^>]*>/gi)].map((match) => attributes(match[0])).filter((tag) => tag.rel === "canonical");
  assert.deepEqual(canonicals.map((tag) => tag.href), [canonical]);
  for (const tag of meta.filter((entry) => /^(robots|googlebot)$/i.test(entry.name || ""))) {
    assert.doesNotMatch(tag.content || "", /noindex/i, "Terms unexpectedly became noindex");
  }
}

try {
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 1 && args[0] === "--built") || (args.length === 2 && args[0] === "--base"), "usage: npm run terms:check [-- --built | -- --base http://127.0.0.1:3100]");
  const source = readFileSync(pagePath, "utf8");
  const expectedMarkup = checkSource(source);
  const negativeCases = [
    [gameHeading, "Authorized Game File"],
    ["We have not verified personal", "We have verified personal"],
    ["Read these terms of service", "Read these rules"],
    ['href="/contact"', 'href="/missing-contact"'],
    [updated, "Last updated: May 21, 2026"],
    [canonical, "https://example.invalid/terms-of-service"]
  ];
  for (const [original, changed] of negativeCases) {
    assert.ok(source.includes(original), `negative fixture not applied: ${original}`);
    assert.throws(() => checkSource(source.replace(original, changed)), undefined, `negative fixture was accepted: ${original}`);
  }
  console.log("TERMS-001 source passed: exact approved copy/date, 1 H1, 7 H2s, 8 paragraphs, KW-02 count 3, two links, frozen remaining source.");
  console.log(`Fail-closed negative fixtures: ${negativeCases.length} rejected (rights, keyword, link, date and metadata regressions).`);

  if (args[0] === "--built") {
    const html = readFileSync(resolve(projectRoot, ".next/server/app/terms-of-service.html"), "utf8");
    checkDocument(html, expectedMarkup);
    assert.throws(() => checkDocument(html.replace(canonical, "https://example.invalid/terms"), expectedMarkup));
    assert.throws(() => checkDocument(html.replace(gameHeading, "Authorized Game File"), expectedMarkup));
    console.log("TERMS-001 built HTML passed: exact copy, title/description/canonical, no noindex, source/render parity; 2 raw negative fixtures rejected.");
    console.log("This is an offline build-artifact check. HTTP status/headers, browser interactions and production release remain NOT verified.");
  } else if (args.length) {
    const base = new URL(args[1]);
    assert.ok(["http:", "https:"].includes(base.protocol));
    assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(base.hostname), "this pre-deployment check requires a local build, not production");
    assert.ok(base.pathname === "/" && !base.search && !base.hash && !base.username && !base.password, "--base must be a local origin");
    const url = new URL("/terms-of-service", base);
    const response = await fetch(url, { redirect: "manual", signal: AbortSignal.timeout(10_000) });
    assert.equal(response.status, 200, `Terms returned HTTP ${response.status}`);
    assert.match(response.headers.get("content-type") || "", /text\/html/i);
    assert.doesNotMatch(response.headers.get("x-robots-tag") || "", /noindex/i);
    const html = await response.text();
    checkDocument(html, expectedMarkup);
    assert.throws(() => checkDocument(html.replace(canonical, "https://example.invalid/terms"), expectedMarkup));
    assert.throws(() => checkDocument(html.replace(gameHeading, "Authorized Game File"), expectedMarkup));
    console.log(`TERMS-001 raw local production passed: ${url}; HTTP 200, exact copy, title/description/canonical, no noindex, source/render parity; 2 raw negative fixtures rejected.`);
  } else {
    console.log("Raw HTTP, browser, actual licenses and production release are NOT verified by a source-only run.");
  }
} catch (error) {
  console.error(`TERMS-001 check failed: ${error.message}`);
  process.exitCode = 1;
}
