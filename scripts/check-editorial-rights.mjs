const decode = (value) => value.replace(/&#(?:x([0-9a-f]+)|(\d+));/gi, (_, hex, dec) => String.fromCodePoint(parseInt(hex || dec, hex ? 16 : 10)))
  .replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
const plain = (value) => decode(value.replace(/<[^>]*>/g, " ")).replace(/\s+/g, " ").trim();
const contents = (value, tag) => [...value.matchAll(new RegExp("<" + tag + "\\b[^>]*>([\\s\\S]*?)<\\/" + tag + ">", "gi"))].map((match) => plain(match[1]));
const attributes = (tag) => Object.fromEntries([...tag.matchAll(/([\w:-]+)="([^"]*)"/g)].map((match) => [match[1].toLowerCase().replace(/^classname$/, "class"), decode(match[2])]));

function checkMarkup(markup) {
  const mains = [...markup.matchAll(/<main\b[^>]*>([\s\S]*?)<\/main>/gi)];
  assert.equal(mains.length, 1, "exactly one main is required");
  const main = mains[0][1];
  assert.doesNotMatch(mains[0][0], /<script\b|\shidden(?:\s|[=>])|aria-hidden="true"|(?:class|className)="[^"]*\b(?:hidden|sr-only)\b|style="[^"]*(?:display\s*:\s*none|visibility\s*:\s*hidden)/i,
    "main copy must not be hidden or replaced by scripts");
  for (const tag of ["h1", "h2", "h3"]) {
    assert.deepEqual(contents(main, tag), headings[tag], tag + " structure or text changed");
  }
  const paragraphs = contents(main, "p");
  assert.equal(paragraphs.length, 10, "paragraph structure changed");
  const approvedParagraph = edits.find((edit) => edit.id === "source-rights-paragraph").new;
  assert.equal(paragraphs.filter((text) => text === approvedParagraph).length, 1, "source/rights paragraph differs from confirmed copy");
  assert.equal(paragraphs.filter((text) => text === acceptedKwCopy).length, 1, "accepted KW-02 sentence changed");
  assert.equal((plain(main).match(/editorial policy/gi) || []).length, 3, "KW-02 main coverage changed");
  assert.doesNotMatch(plain(main), /Editorial Policy for Original Content and Assets|Gallery examples and visual explanations are created for this site/i);
  const links = [...main.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi)].map((match) => ({
    href: attributes(match[1]).href,
    text: plain(match[2])
  }));
  assert.deepEqual(links, expectedLinks, "main link order, destinations or copy changed");
  // Source uses className, SSR uses class; all other main tag/attribute boundaries must match.
  const structure = [...mains[0][0].matchAll(/<\/?([a-z][\w-]*)\b[^>]*>/gi)].map((match) => ({
    tag: match[1].toLowerCase(),
    closing: match[0].startsWith("</"),
    attributes: attributes(match[0])
  }));
  return { paragraphs, headings, links, structure };
}

function checkSource(source) {
  let frozen = source;
  for (const edit of edits) {
    assert.equal(frozen.split(edit.new).length - 1, 1, edit.id + " must appear exactly once");
    assert.ok(!frozen.includes(edit.old), edit.id + " still contains obsolete copy");
    frozen = frozen.replace(edit.new, "__EDITORIAL_REGION_" + edit.id + "__");
  }
  assert.equal(createHash("sha256").update(frozen).digest("hex"), expectedFrozenHash,
    "unapproved change outside the five regions: metadata/schema, imports, layout, links or other copy");
  return checkMarkup(source);
}

function checkDocument(html, expectedMarkup) {
  assert.deepEqual(checkMarkup(html), expectedMarkup, "raw HTML differs from approved source");
  const head = html.match(/<head\b[^>]*>([\s\S]*?)<\/head>/i)?.[1];
  assert.ok(head, "raw HTML head is missing");
  assert.deepEqual(contents(head, "title"), [title + " | My Square Face Icon"]);
  const meta = [...head.matchAll(/<meta\b[^>]*>/gi)].map((match) => attributes(match[0]));
  const expectMeta = (key, value, attribute = "name") => {
    assert.deepEqual(meta.filter((tag) => tag[attribute] === key).map((tag) => tag.content), [value], key + " mismatch");
  };
  expectMeta("description", metadata.description);
  const openGraph = {
    "og:title": metadata.openGraph.title,
    "og:description": metadata.openGraph.description,
    "og:url": canonical,
    "og:image": new URL(metadata.openGraph.images[0], canonical).href,
    "og:type": metadata.openGraph.type
  };
  for (const [key, value] of Object.entries(openGraph)) expectMeta(key, value, "property");
  const twitter = {
    "twitter:card": metadata.twitter.card,
    "twitter:title": metadata.twitter.title,
    "twitter:description": metadata.twitter.description,
    "twitter:image": new URL(metadata.twitter.images[0], canonical).href
  };
  for (const [key, value] of Object.entries(twitter)) expectMeta(key, value);
  const canonicals = [...head.matchAll(/<link\b[^>]*>/gi)].map((match) => attributes(match[0])).filter((tag) => tag.rel === "canonical");
  assert.deepEqual(canonicals.map((tag) => tag.href), [canonical]);
  for (const tag of meta.filter((entry) => /^(robots|googlebot)$/i.test(entry.name || ""))) {
    assert.doesNotMatch(tag.content || "", /(?:noindex|none)/i, "Editorial unexpectedly became noindex");
  }
  const schemas = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)]
    .filter((match) => attributes(match[1]).type === "application/ld+json")
    .map((match) => JSON.parse(match[2]));
  assert.deepEqual(schemas, expectedSchemas, "WebPage schema changed");
}

function rejectNegatives(input, cases, check, label) {
  for (const [original, changed] of cases) {
    assert.ok(input.includes(original), label + " negative fixture not applied: " + original);
    assert.notEqual(original, changed, label + " negative fixture must change input");
    assert.throws(() => check(input.replace(original, changed)), undefined,
      label + " negative fixture was accepted: " + original);
  }
  return cases.length;
}

function checkRawNegatives(html, expectedMarkup) {
  const cases = [
    ...edits.map((edit) => [edit.new, edit.old]),
    ["remain unverified.", "are authorized."],
    [canonical, "https://example.invalid/editorial-policy"],
    ["<title>Editorial Policy | My Square Face Icon</title>", "<title>Unapproved title</title>"],
    ["<h1>Editorial Policy</h1>", "<h1>Unapproved heading</h1>"],
    ['"@type":"WebPage"', '"@type":"Product"'],
    ['href="/contact">contact page</a>', 'href="/missing-contact">contact page</a>'],
    ["</head>", '<meta name="robots" content="noindex"/></head>'],
    ['<main class="resource-page">', '<main class="resource-page" hidden>'],
    [acceptedKwCopy, "Editorial standards apply."],
    ["</main>", "<p>Unexpected extra content.</p></main>"]
  ];
  return rejectNegatives(html, cases, (candidate) => checkDocument(candidate, expectedMarkup), "raw HTML");
}

